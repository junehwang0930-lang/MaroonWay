"""Apply manual instructor-name review notes without changing Registrar source data.

Run from the MaroonWay project: py scripts/apply_name_reviews.py
Needs: data/maroonway.db and data/manual_instructor_reviews.csv
"""
from __future__ import annotations

import csv
import shutil
import sqlite3
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "data"
DB_PATH = DATA / "maroonway.db"
REVIEWS_PATH = DATA / "manual_instructor_reviews.csv"
BACKUP_PATH = DATA / "maroonway_before_name_reviews.db"
EXPORT_PATH = DATA / "grade_sections_reviewed.csv"


def main() -> None:
    if not DB_PATH.is_file():
        raise SystemExit("Missing data/maroonway.db — first run: py pipeline.py import-pdf")
    if not REVIEWS_PATH.is_file():
        raise SystemExit("Missing data/manual_instructor_reviews.csv")

    with REVIEWS_PATH.open(encoding="utf-8-sig", newline="") as handle:
        reviews = list(csv.DictReader(handle))
    if not reviews:
        raise SystemExit("No reviews to apply")

    # Make a backup just once. Re-running the script will not replace it.
    if not BACKUP_PATH.exists():
        with sqlite3.connect(DB_PATH) as source, sqlite3.connect(BACKUP_PATH) as target:
            source.backup(target)
        print(f"Backup created: {BACKUP_PATH}")

    with sqlite3.connect(DB_PATH) as con:
        con.row_factory = sqlite3.Row
        existing_columns = {r[1] for r in con.execute("PRAGMA table_info(grade_sections)")}
        for column in ("reviewed_instructor_name", "name_review_status", "name_review_note"):
            if column not in existing_columns:
                con.execute(f"ALTER TABLE grade_sections ADD COLUMN {column} TEXT")

        seen = set()
        for review in reviews:
            code = review["section_code"].strip().upper()
            try:
                subject, course_number, section = code.split("-", 2)
            except ValueError as exc:
                raise SystemExit(f"Invalid section code: {code}") from exc
            term = review["term"].strip().upper()
            expected_raw = review["instructor_as_reported"].strip()
            display_name = review["reviewed_instructor_name"].strip()
            status = review["review_status"].strip().lower()
            note = review["review_note"].strip()
            college = review.get("college", "").strip().upper()
            key = (term, subject, course_number, section)
            review_key = (*key, college)
            if review_key in seen:
                raise SystemExit(f"Duplicate manual review entry: {term} {code}")
            seen.add(review_key)
            if status not in {"candidate", "verified"} or not display_name:
                raise SystemExit(f"Invalid review status/name for {code}")

            matches = con.execute(
                """SELECT id, instructor_as_reported FROM grade_sections
                   WHERE term=? AND subject=? AND course_number=? AND section=?
                   AND (?='' OR college=?)""",
                (*key, college, college),
            ).fetchall()
            if len(matches) > 1:
                raise SystemExit(f"Ambiguous College for {term} {code}; add an explicit college CSV column")
            match = matches[0] if matches else None
            if match is None:
                raise SystemExit(f"No database row matches {term} {code}; no changes saved")
            if match["instructor_as_reported"] != expected_raw:
                raise SystemExit(
                    f"Instructor mismatch for {code}: database has "
                    f"{match['instructor_as_reported']!r}, manual review expects {expected_raw!r}"
                )
            con.execute(
                """UPDATE grade_sections SET reviewed_instructor_name=?,
                   name_review_status=?, name_review_note=? WHERE id=?""",
                (display_name, status, note, match["id"]),
            )
            print(f"Added review: {term} {code}: {expected_raw} -> {display_name} ({status})")
        con.commit()

        # A separate export preserves the original grade_sections.csv generated by pipeline.py.
        rows = con.execute(
            """SELECT term, college, subject, course_number, section,
                 instructor_as_reported, reviewed_instructor_name, name_review_status,
                 name_review_note, a, b, c, d, f, af_total, gpa_reported,
                 i_count, s_count, u_count, q_count, x_count, enrollment_total,
                 quality_status, source_page, source_url
                 FROM grade_sections ORDER BY subject, course_number, section"""
        ).fetchall()
        with EXPORT_PATH.open("w", encoding="utf-8", newline="") as handle:
            writer = csv.writer(handle)
            if rows:
                writer.writerow(rows[0].keys())
                writer.writerows(tuple(row) for row in rows)
    print(f"Reviewed export: {EXPORT_PATH}")
    print("Original instructor_as_reported and automatic quality_status remain unchanged.")
    print("'candidate' means a suggested match, not a verified professor identity.")


if __name__ == "__main__":
    main()
